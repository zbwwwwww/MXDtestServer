    var m0 = cm.getMonsterLifeFactory(8800000);
    var spawned = false;
    try {
        map.spawnMonsterOnGroundBelow(m0, new Packages.java.awt.Point(pos.x, pos.y));
        spawned = true;
    } catch (e) {
        spawned = false;
    }

